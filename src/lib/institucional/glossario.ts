/** Glossário na língua pedida (mesmos ids e categorias do português; sem tradução de um id, fica o português). Pura. */
export function glossaryFor(loc: Locale): GlossaryTerm[] {
  if (loc !== 'es') return GLOSSARY;
  return GLOSSARY.map((t) => {
    const e = GLOSSARY_ES[t.id];
    return e ? { ...t, term: e.term, aka: e.aka, def: e.def } : t;
  });
}

export function glossaryCategoryLabel(loc: Locale): Record<GlossaryCategory, string> {
  return loc === 'es' ? GLOSSARY_CATEGORY_LABEL_ES : GLOSSARY_CATEGORY_LABEL;
}
